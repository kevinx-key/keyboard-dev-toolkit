// 由「键圈术语资料包」JSON 生成前端可打包的术语数据模块。
// 用法: node scripts/gen-community-glossary.mjs
// 产物: src/lib/community-glossary.generated.ts（勿手改；改术语请改 JSON 后重跑本脚本）

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = path.join(root, "docs", "键圈术语资料包", "键圈术语库.json");
const out = path.join(root, "src", "lib", "community-glossary.generated.ts");

const data = JSON.parse(fs.readFileSync(src, "utf8"));

const byCat = new Map();
for (const t of data.terms) {
  if (!byCat.has(t.category)) byCat.set(t.category, []);
  byCat.get(t.category).push(t);
}

const fmt = (t) => {
  const abbr = t.abbr && t.abbr !== t.en ? `（${t.abbr}）` : "";
  const def = t.definition ? ` — ${t.definition}` : "";
  return `- **${t.en}**${abbr} · ${t.cn}${def}`;
};

const sections = [];
for (const [cat, terms] of byCat) {
  sections.push([cat, `## ${cat}\n${terms.map(fmt).join("\n")}`]);
}

const header = `// AUTO-GENERATED by scripts/gen-community-glossary.mjs — DO NOT EDIT BY HAND.
// Source: docs/键圈术语资料包/键圈术语库.json（键圈社区术语；供 AI 助手按需读取）
// 共 ${data.terms.length} 条，${byCat.size} 类。

`;

const body = [];
body.push("export const COMMUNITY_GLOSSARY_CATEGORIES = [");
for (const [cat] of sections) body.push(`  ${JSON.stringify(cat)},`);
body.push("] as const;");
body.push("");
body.push(`export const COMMUNITY_GLOSSARY_COUNT = ${data.terms.length};`);
body.push("");
body.push("const SECTIONS: Record<string, string> = {");
for (const [cat, text] of sections) body.push(`  ${JSON.stringify(cat)}: ${JSON.stringify(text)},`);
body.push("};");
body.push("");
body.push(`export const COMMUNITY_GLOSSARY_FULL = Object.values(SECTIONS).join("\\n\\n");`);
body.push("");
body.push("/** 按类别读取术语（类别名见 COMMUNITY_GLOSSARY_CATEGORIES）；未知类别返回 null。 */");
body.push("export function glossaryByCategory(category: string): string | null {");
body.push("  return SECTIONS[category] ?? null;");
body.push("}");

fs.writeFileSync(out, header + body.join("\n") + "\n", "utf8");
console.log(`Wrote ${out} (${data.terms.length} terms, ${byCat.size} categories)`);
