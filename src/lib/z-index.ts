/**
 * 全局层叠顺序（UI 叠放唯一约定）
 *
 * 页面里同时存在：画布内选区、常驻 AI 悬浮球/面板、下拉菜单、取色器/右键菜单、
 * 模态对话框、全屏导出进度。若各处随意写 z-index，很容易出现
 * 「弹窗被悬浮面板压住」「下拉被属性区盖住」「固定层被父级 stacking context 限制」。
 *
 * 统一按下面 5 层叠放（数值越大越靠上）：
 *
 *   画布内部覆盖层 100
 *     └ 选中框等（只与画布内容比较）
 *   AI 常驻悬浮面板 9999
 *     └ 球 / 面板：高于页面内容，但低于所有临时浮层
 *   临时浮层（取色器 / 右键菜单 / 提示） 10000
 *     └ 高于 AI 面板
 *   下拉菜单（顶栏 / 画布工具栏） 10050
 *     └ 临时菜单始终高于 AI 面板与取色器等浮层
 *   模态对话框（帮助 / 关于 / 备份 / STP 确认 / 步骤设置） 20000
 *     └ 模态遮罩必须盖住悬浮面板与所有浮层
 *   全屏导出遮罩（STP / QMK） 99999
 *     └ 最高的进度遮罩
 *
 * 注意：父级一旦有 z-index（非 auto）/ transform / filter / backdrop-filter，
 * 就会形成 stacking context，子元素的 z-index 只在该上下文内比较。
 * 画布工具栏本身不设 z-index，让下拉参与全局层叠；
 * 顶栏 .kle-toolbar 例外地保留 z-index:10（位于页面内容之上），
 * 其下拉菜单只在该上下文内比较（菜单位于页面顶部，不会与画布浮层大面积重叠）。
 * 颜色选择器已 portal 到 body，避免被 .theme-future .kle-tabpanel 的 backdrop-filter 困住。
 */
export const Z_INDEX = {
  /** 画布内部覆盖层（选中框等） */
  canvasOverlay: 100,
  /** AI 常驻悬浮球 / 面板 */
  floatingPanel: 9999,
  /** 临时浮层：取色器、右键菜单 */
  popover: 10000,
  /** 下拉菜单：顶栏 / 画布工具栏 */
  menu: 10050,
  /** 模态对话框 */
  modal: 20000,
  /** 全屏进度遮罩 */
  fullscreen: 99999,
} as const;
